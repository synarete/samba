/* opcodes and operations are much smaller */
#define MAX_SCAN	4096

static uint8_t fill_byte;

static char *print_to_string(TALLOC_CTX *mem_ctx,
			     void (*fn)(uint32_t v, FILE *fp),
			     uint32_t v)
{
	char *buf = NULL;
	size_t len = 0;
	FILE *fp = NULL;
	char *ret = NULL;

	fp = open_memstream(&buf, &len);
	assert(fp != NULL);
	fn(v, fp);
	fclose(fp);

	ret = talloc_strdup(mem_ctx, buf);
	assert(ret != NULL);
	free(buf);
	return ret;
}

static void print_comment(const char *txt)
{
	const char *p = txt;

	while (*p != '\0') {
		const char *e = strchr(p, '\n');
		size_t len;
		size_t plen;

		if (e == NULL) {
			len = strlen(p);
		} else {
			len = e - p;
		}
		/* without trailing whitespace */
		plen = len;
		while (plen > 0 && isspace((unsigned char)p[plen - 1])) {
			plen--;
		}
		printf("#\t%.*s\n", (int)plen, p);
		p += len;
		if (*p == '\n') {
			p++;
		}
	}
}

static void print_packet_comment(uint8_t *buf, size_t buflen)
{
	char *txt = NULL;
	size_t len = 0;
	FILE *fp = NULL;

	fp = open_memstream(&txt, &len);
	assert(fp != NULL);
	ctdb_packet_print(buf, buflen, fp);
	fclose(fp);

	print_comment(txt);
	free(txt);
}

static void print_hex(const uint8_t *buf, size_t buflen)
{
	size_t ofs;

	for (ofs = 0; ofs < buflen; ofs += 16) {
		size_t i;

		printf("\t[%04zx]", ofs);
		for (i = ofs; i < MIN(ofs + 16, buflen); i++) {
			if (i == ofs + 8) {
				printf(" ");
			}
			printf(" %02x", buf[i]);
		}
		printf("\n");
	}
}

static void print_sample(const char *name,
			 uint8_t *buf,
			 size_t buflen,
			 const char *status,
			 bool comment)
{
	printf("sample %s length(%zu)%s%s {\n",
	       name,
	       buflen,
	       status[0] != '\0' ? " " : "",
	       status);
	print_hex(buf, buflen);
	printf("}\n");
	if (comment) {
		print_packet_comment(buf, buflen);
	}
	printf("\n");
}

/*
 * Each sample uses its own seed, so changing the
 * fill function of one type only changes the samples
 * using that type.
 */
static void seed_sample(const char *name)
{
	uint64_t h = 0xcbf29ce484222325ULL;
	const char *p;

	/* FNV-1a */
	for (p = name; *p != '\0'; p++) {
		h ^= (uint8_t)*p;
		h *= 0x100000001b3ULL;
	}

	protocol_test_srandom(h);
}

static void *alloc_filled(TALLOC_CTX *mem_ctx, size_t size)
{
	void *p = talloc_size(mem_ctx, size);

	assert(p != NULL);
	memset(p, fill_byte, size);
	return p;
}

/*
 * A valid header for the given operation like in the real code,
 * so the packet can be printed in the comment.
 */
static struct ctdb_req_header *fill_header(TALLOC_CTX *mem_ctx,
					   uint32_t operation)
{
	struct ctdb_req_header *h = NULL;
	uint32_t generation = rand32();
	uint32_t destnode = rand32();
	uint32_t srcnode = rand32();
	uint32_t reqid = rand32();

	h = alloc_filled(mem_ctx, sizeof(*h));
	ctdb_req_header_fill(h, generation, operation,
			     destnode, srcnode, reqid);
	return h;
}

static void sample_ctdb_req_header(void)
{
	TALLOC_CTX *mem_ctx = talloc_new(NULL);
	const char *name = "ctdb_req_header";
	struct ctdb_req_header *h = NULL;
	struct ctdb_req_header h2;
	uint8_t *buf = NULL, *buf2 = NULL;
	size_t buflen, np = 0;
	const char *status = "";
	int ret;

	assert(mem_ctx != NULL);
	seed_sample(name);

	h = alloc_filled(mem_ctx, sizeof(*h));
	fill_ctdb_req_header(h);
	buflen = ctdb_req_header_len(h);
	buf = talloc_zero_size(mem_ctx, buflen);
	assert(buf != NULL);
	ctdb_req_header_push(h, buf, &np);
	assert(np == buflen);

	np = 0;
	ret = ctdb_req_header_pull(buf, buflen, &h2, &np);
	if (ret != 0) {
		status = talloc_asprintf(mem_ctx, "pull_error(%d)", ret);
	} else {
		buf2 = talloc_zero_size(mem_ctx, buflen);
		assert(buf2 != NULL);
		np = 0;
		ctdb_req_header_push(&h2, buf2, &np);
		if (np != buflen || memcmp(buf, buf2, buflen) != 0) {
			status = "repush_mismatch";
		}
	}
	assert(status != NULL);

	print_sample(name, buf, buflen, status, false);
	talloc_free(mem_ctx);
}

/*
 * The packets are allocated with ctdb_allocate_pkt()
 * like in the real code, the pulled packet is pushed
 * again in order to check that it matches.
 */
#define SAMPLE_PACKET(TYPE, NAME, OPER, FILL_ARGS, PULL_ARGS) \
static void sample_ ##NAME(TALLOC_CTX *mem_ctx, \
			   const char *name, \
			   uint32_t opcode, \
			   uint64_t srvid) \
{ \
	struct ctdb_req_header *h = NULL; \
	struct ctdb_req_header h2; \
	TYPE *c = NULL; \
	TYPE *c2 = NULL; \
	uint8_t *pkt = NULL, *pkt2 = NULL; \
	size_t pkt_len, pkt2_len, buflen; \
	const char *status = ""; \
	int ret; \
\
	(void)opcode; \
	(void)srvid; \
	seed_sample(name); \
	h = fill_header(mem_ctx, OPER); \
	c = alloc_filled(mem_ctx, sizeof(*c)); \
	fill_ ##NAME FILL_ARGS; \
	buflen = NAME ##_len(h, c); \
	ret = ctdb_allocate_pkt(mem_ctx, buflen, &pkt, &pkt_len); \
	assert(ret == 0); \
	ret = NAME ##_push(h, c, pkt, &pkt_len); \
	assert(ret == 0); \
\
	c2 = talloc_zero(mem_ctx, TYPE); \
	assert(c2 != NULL); \
	ret = NAME ##_pull PULL_ARGS; \
	if (ret != 0) { \
		status = talloc_asprintf(mem_ctx, "pull_error(%d)", ret); \
		goto done; \
	} \
	buflen = NAME ##_len(&h2, c2); \
	ret = ctdb_allocate_pkt(mem_ctx, buflen, &pkt2, &pkt2_len); \
	assert(ret == 0); \
	ret = NAME ##_push(&h2, c2, pkt2, &pkt2_len); \
	if (ret != 0) { \
		status = talloc_asprintf(mem_ctx, "repush_error(%d)", ret); \
		goto done; \
	} \
	if (pkt_len != pkt2_len || memcmp(pkt, pkt2, pkt_len) != 0) { \
		status = "repush_mismatch"; \
	} \
done: \
	assert(status != NULL); \
	print_sample(name, pkt, pkt_len, status, true); \
}

