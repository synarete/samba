static const char *srvid_name(uint64_t srvid)
{
	size_t i;

	for (i = 0; i < ARRAY_SIZE(srvids); i++) {
		if (srvids[i].srvid == srvid) {
			/* without the CTDB_SRVID_ prefix */
			return srvids[i].name + strlen("CTDB_SRVID_");
		}
	}

	abort();
}

static void sample_messages(void)
{
	size_t i;

	for (i = 0; i < ARRAY_SIZE(message_srvids); i++) {
		TALLOC_CTX *mem_ctx = talloc_new(NULL);
		uint64_t srvid = message_srvids[i];
		const char *name = NULL;

		assert(mem_ctx != NULL);
		name = talloc_asprintf(mem_ctx,
				       "ctdb_req_message@%s",
				       srvid_name(srvid));
		assert(name != NULL);
		sample_ctdb_req_message(mem_ctx, name, 0, srvid);
		talloc_free(mem_ctx);
	}
}

