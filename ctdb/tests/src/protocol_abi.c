static void print_opcodes(void)
{
	TALLOC_CTX *mem_ctx = talloc_new(NULL);
	uint32_t opcode;

	assert(mem_ctx != NULL);
	printf("enum ctdb_controls {\n");
	for (opcode = 0; opcode < MAX_SCAN; opcode++) {
		if (!opcode_known(mem_ctx, opcode)) {
			continue;
		}
		printf("\tCTDB_CONTROL_%s = %u\n",
		       opcode_name(mem_ctx, opcode),
		       opcode);
	}
	printf("}\n\n");
	talloc_free(mem_ctx);
}

