/*
 * Prints the wire format of the ctdb protocol, which is
 * used between the nodes of a cluster and between ctdbd
 * and its clients, in the same format as the ndr_abi_<idl>
 * binaries generated by 'pidl --ndr-abi', see
 * librpc/ndr/ndr_abi.h.
 *
 * The build compares the output with
 * ctdb/protocol/ABI/ctdb_protocol.ndrabi.
 *
 * The output consists of:
 *
 * 1. 'enum' blocks with the values of the packet operations,
 *    the control opcodes and the srvids. New values can be
 *    added, but existing values can't be changed.
 *
 * 2. A 'struct' block with the names of the tunables in the
 *    order of struct ctdb_tunable_list, which is used on the
 *    wire as is (CTDB_CONTROL_GET_ALL_TUNABLES), so it can't
 *    be changed at all.
 *
 * 3. 'sample' blocks with a packet of each type, every
 *    control opcode (request and reply) and some srvids,
 *    filled with deterministic pseudo random values,
 *    arrays and buffers have at most 3 elements.
 *    The packets are pushed, pulled and pushed again,
 *    a mismatch is recorded in the sample.
 *
 * The ctdb protocol uses the host byte order and the
 * alignment depends on the size of pointers (see
 * ctdb_padding_push()), the samples are only checked on
 * 64-bit little endian hosts.
 *
 * As the build runs this twice with different values for
 * TALLOC_FREE_FILL, the structures are initialized with that
 * value before they are filled, so the output changes if
 * uninitialized memory (e.g. padding) ends up on the wire.
 */

