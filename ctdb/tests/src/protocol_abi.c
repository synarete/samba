static const char *opcode_name(TALLOC_CTX *mem_ctx, uint32_t opcode)
{
	return print_to_string(mem_ctx, ctdb_opcode_print, opcode);
}

static bool opcode_known(TALLOC_CTX *mem_ctx, uint32_t opcode)
{
	return strncmp(opcode_name(mem_ctx, opcode), "UNKNOWN(", 8) != 0;
}

static uint32_t num_opcodes(void)
{
	TALLOC_CTX *mem_ctx = talloc_new(NULL);
	uint32_t opcode;
	uint32_t num = 0;

	assert(mem_ctx != NULL);
	for (opcode = 0; opcode < MAX_SCAN; opcode++) {
		if (opcode_known(mem_ctx, opcode)) {
			num = opcode + 1;
		}
	}
	talloc_free(mem_ctx);

	return num;
}

static void sample_controls(void)
{
	uint32_t num = num_opcodes();
	uint32_t opcode;

	for (opcode = 0; opcode < num; opcode++) {
		TALLOC_CTX *mem_ctx = talloc_new(NULL);
		const char *name = NULL;

		assert(mem_ctx != NULL);
		name = talloc_asprintf(mem_ctx,
				       "ctdb_req_control@%s",
				       opcode_name(mem_ctx, opcode));
		assert(name != NULL);
		sample_ctdb_req_control(mem_ctx, name, opcode, 0);
		talloc_free(mem_ctx);
	}

	for (opcode = 0; opcode < num; opcode++) {
		TALLOC_CTX *mem_ctx = talloc_new(NULL);
		const char *name = NULL;

		assert(mem_ctx != NULL);
		name = talloc_asprintf(mem_ctx,
				       "ctdb_reply_control@%s",
				       opcode_name(mem_ctx, opcode));
		assert(name != NULL);
		sample_ctdb_reply_control(mem_ctx, name, opcode, 0);
		talloc_free(mem_ctx);
	}
}

